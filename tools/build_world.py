"""Write worlds/robot_cell.wbt: FANUC LR Mate 200iD + UR5e (Robotiq 2F-85 grippers), conveyor, PLC.

    python tools/build_world.py [--out worlds/robot_cell.wbt]

The UR5e and the Robotiq 2F-85 are official Webots PROTOs, loaded from the Webots GitHub repository
(R2025a) on first use and cached by Webots; the FANUC PROTO is converted from the ROS-Industrial
description (protos/FanucLrMate200iD.proto). Grippers, emitters and receivers sit in the toolSlots.

Pad friction: the finger motors of the Webots Robotiq2f85Gripper are limited to 0.1 N.m (a fixed
value inside the official PROTO), far below the 20-235 N grip of the real gripper; with a realistic
pad friction the 50 g cube slides in the pads as soon as the arm accelerates. The pad/cube contact
friction is therefore raised to 5 to emulate the real grip force, and a spinning friction
(rollingFriction 0 0 0.01) is added: ODE does not resist the rotation of the cube about the pad
normal by default, and the cube pivoted out of the UR5e gripper while it was flipped.
"""
import argparse
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
sys.path.insert(0, HERE)
from cell_layout import BELT_TOP, CUBE, CUBE_MASS, FANUC_BASE, FANUC_YAW, I, O, UR_BASE, UR_YAW  # noqa: E402

WEBOTS = "https://raw.githubusercontent.com/cyberbotics/webots/R2025a/projects"


def first_pose(name):
    with open(os.path.join(ROOT, "motions", name)) as f:
        f.readline()
        return [float(v) for v in f.readline().strip().split(",")[2:]]


def radio():
    return 'Emitter { name "emitter" channel 2 } Receiver { name "receiver" channel 1 }'


def build():
    qu = first_pose("ur5e_cell.motion")
    ur_via = f"via:{qu[0]:.5f},{-math.pi / 2:.5f},0"        # arm straight up first (zero pose lies near the floor)
    slats = "\n".join(
        f"    DEF SLAT_{k} Pose {{ translation 0 {1.09 - 0.05 * k:.2f} 0.351 children [ Shape {{ appearance "
        f"PBRAppearance {{ baseColor 0.3 0.3 0.32 roughness 0.8 metalness 0 }} geometry Box {{ size 0.09 0.008 0.002 }} }} ] }}"
        for k in range(23))
    colors = ["0.9 0.75 0.1", "0.1 0.75 0.85", "0.85 0.2 0.6"]
    cubes = []
    for k, c in enumerate(colors):
        pos = f"{I[0]} {I[1]} {BELT_TOP + CUBE / 2 + 0.0002:.4f}" if k == 0 else f"{10.0 + 0.1 * k:.1f} 10 -1.0795"
        cubes.append(
            f'DEF CUBE_{k} Solid {{\n  translation {pos}\n  name "cube {k}"\n  contactMaterial "cube"\n'
            f'  children [ Shape {{ appearance PBRAppearance {{ baseColor {c} roughness 0.5 metalness 0 }} '
            f'geometry Box {{ size {CUBE} {CUBE} {CUBE} }} }} ]\n'
            f'  boundingObject Box {{ size {CUBE} {CUBE} {CUBE} }}\n'
            f'  physics Physics {{ density -1 mass {CUBE_MASS} }}\n}}')
    return f"""#VRML_SIM R2025a utf8
# Robot cell: FANUC LR Mate 200iD + UR5e, both with a Robotiq 2F-85, in-air hand-over, conveyor and PLC.
# Generated by tools/build_world.py -- edit tools/cell_layout.py / the PROTOs, not this file.

EXTERNPROTO "{WEBOTS}/robots/universal_robots/protos/UR5e.proto"
EXTERNPROTO "{WEBOTS}/devices/robotiq/protos/Robotiq2f85Gripper.proto"
EXTERNPROTO "../protos/FanucLrMate200iD.proto"
EXTERNPROTO "../protos/BeltConveyor.proto"
EXTERNPROTO "../protos/OutputBin.proto"
EXTERNPROTO "../protos/MobilePlexiCell.proto"

WorldInfo {{
  info [ "FANUC LR Mate 200iD + UR5e hand-over cell, one 50 g cube every 14.4 s" ]
  title "Robot cell"
  basicTimeStep 8
  coordinateSystem "ENU"
  contactProperties [
    ContactProperties {{ material1 "ROBOTIQ gripper pad" material2 "cube" coulombFriction [ 5 ] rollingFriction 0 0 0.01 softCFM 0.0001 }}
    ContactProperties {{ material1 "belt" material2 "cube" coulombFriction [ 0 ] bounce 0 }}
  ]
}}
Viewpoint {{
  orientation -0.1834 0.0741 0.9802 2.3871
  position 5.0 -4.2 2.2
}}
Background {{ skyColor [ 0.82 0.86 0.92 ] }}
DirectionalLight {{ direction -0.4 -0.6 -1 intensity 2.4 castShadows TRUE }}
DirectionalLight {{ direction 0.5 0.4 -0.6 intensity 1.0 }}
DirectionalLight {{ direction 0.0 -0.8 -0.3 intensity 0.5 }}
DEF FLOOR Solid {{
  translation 0 0 -1.10
  name "floor"
  children [ Shape {{ appearance PBRAppearance {{ baseColor 0.20 0.22 0.25 roughness 0.35 metalness 0.15 }} geometry DEF FLOOR_GEO Plane {{ size 10 10 }} }} ]
  boundingObject USE FLOOR_GEO
}}
MobilePlexiCell {{ translation 0.50 -0.05 0 size 1.70 1.25 height 1.15 floorZ -1.10 shelfZ -0.85 openingCenterX {I[0] - 0.50:.2f} openingWidth 0.22 openingHeight 0.44 door TRUE doorWidth 0.72 doorCenterX -0.05 }}
DEF FANUC FanucLrMate200iD {{
  translation {FANUC_BASE[0]} {FANUC_BASE[1]} {FANUC_BASE[2]}
  rotation 0 0 1 {FANUC_YAW:.5f}
  name "fanuc"
  controller "cell_robot"
  controllerArgs [ "../../motions/fanuc_cell.motion" ]
  toolSlot [ DEF FANUC_GRIP Robotiq2f85Gripper {{ }} {radio()} ]
}}
DEF UR_PLATE Solid {{
  translation {UR_BASE[0]} {UR_BASE[1]} {UR_BASE[2] / 2}
  name "UR5e base plate"
  children [ Shape {{ appearance PBRAppearance {{ baseColor 0.3 0.32 0.35 roughness 0.6 metalness 0.4 }} geometry DEF URP Box {{ size 0.2 0.2 {UR_BASE[2]} }} }} ]
  boundingObject USE URP
}}
DEF UR5E UR5e {{
  translation {UR_BASE[0]} {UR_BASE[1]} {UR_BASE[2]}
  rotation 0 0 1 {UR_YAW:.5f}
  name "ur5e"
  controller "cell_robot"
  controllerArgs [ "../../motions/ur5e_cell.motion" "{ur_via}" ]
  toolSlot [ DEF UR_GRIP Robotiq2f85Gripper {{ rotation 1 0 0 -1.5708 }} {radio()} ]
}}
DEF CONVEYOR BeltConveyor {{
  translation {I[0]} {I[1]} 0
  name "conveyor"
  slats [
{slats}
  ]
}}
DEF OUTPUT_BIN OutputBin {{
  translation {O[0]} {O[1]} 0
}}
""" + "\n".join(cubes) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(ROOT, "worlds", "robot_cell.wbt"))
    a = ap.parse_args()
    with open(a.out, "w") as f:
        f.write(build())
    print("wrote", os.path.relpath(a.out, ROOT))


if __name__ == "__main__":
    main()
