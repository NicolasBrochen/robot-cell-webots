"""Write worlds/robot_cell.wbt from the PROTOs and tools/cell_layout.py.

    python tools/build_world.py [--plain] [--out worlds/robot_cell.wbt]

--plain : opaque robots, no joint frames (default: semi-transparent robots with the
          joint frames shown, X red / Y green / Z blue).
The initial joint positions are read from the first pose of motions/*_cell.motion,
so the robots start exactly in their waiting pose.
"""
import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
sys.path.insert(0, HERE)
from cell_layout import ARM_BASE, ARM_YAW, BELT_TOP, CUBE, CUBE_MASS, I, O, SCARA_BASE  # noqa: E402


def first_pose(name, n):
    with open(os.path.join(ROOT, "motions", name)) as f:
        f.readline()
        return [float(v) for v in f.readline().strip().split(",")[2:2 + n]]


def build(plain):
    tr = 0 if plain else 0.55
    frames = "FALSE" if plain else "TRUE"
    qs = " ".join(f"{v:g}" for v in first_pose("scara_cell.motion", 4))
    qa = " ".join(f"{v:g}" for v in first_pose("arm6_cell.motion", 6))
    slats = "\n".join(
        f"    DEF SLAT_{k} Pose {{ translation 0 {1.09 - 0.05 * k:.2f} 0.351 children [ Shape {{ appearance "
        f"PBRAppearance {{ baseColor 0.3 0.3 0.32 roughness 0.8 metalness 0 }} geometry Box {{ size 0.09 0.008 0.002 }} }} ] }}"
        for k in range(23))
    colors = ["0.9 0.75 0.1", "0.1 0.75 0.85", "0.85 0.2 0.6"]
    cubes = []
    for k, c in enumerate(colors):
        pos = f"{I[0]} {I[1]} {BELT_TOP + CUBE / 2 + 0.0002:.4f}" if k == 0 else f"{10.0 + 0.1 * k:.1f} 10 0.0205"
        cubes.append(
            f'DEF CUBE_{k} Solid {{\n  translation {pos}\n  name "cube {k}"\n  contactMaterial "cube"\n'
            f'  children [ Shape {{ appearance PBRAppearance {{ baseColor {c} roughness 0.5 metalness 0 }} '
            f'geometry Box {{ size {CUBE} {CUBE} {CUBE} }} }} ]\n'
            f'  boundingObject Box {{ size {CUBE} {CUBE} {CUBE} }}\n'
            f'  physics Physics {{ density -1 mass {CUBE_MASS} }}\n}}')
    return f"""#VRML_SIM R2025a utf8
# Robot cell: SCARA + 6-axis arm with an in-air hand-over, infeed conveyor and PLC.
# Generated by tools/build_world.py -- edit the PROTOs / tools/cell_layout.py, not this file.

EXTERNPROTO "../protos/Scara4Axis.proto"
EXTERNPROTO "../protos/Arm6Dof.proto"
EXTERNPROTO "../protos/BeltConveyor.proto"
EXTERNPROTO "../protos/OutputBin.proto"
EXTERNPROTO "../protos/SafetyFence.proto"

WorldInfo {{
  info [ "SCARA + 6-axis hand-over cell, one 50 g cube every 14.4 s" ]
  title "Robot cell"
  basicTimeStep 8
  coordinateSystem "ENU"
  contactProperties [
    ContactProperties {{ material1 "finger" material2 "cube" coulombFriction [ 2 ] softCFM 0.0001 }}
    ContactProperties {{ material1 "belt" material2 "cube" coulombFriction [ 0 ] bounce 0 }}
  ]
}}
Viewpoint {{
  orientation -0.29465 0.12813 0.94698 2.36032
  position 2.55 -1.95 2.25
}}
Background {{ skyColor [ 0.6 0.62 0.65 ] }}
DirectionalLight {{ direction -0.4 -0.6 -1 intensity 2 castShadows TRUE }}
DirectionalLight {{ direction 0.5 0.4 -0.8 intensity 0.6 }}
DEF FLOOR Solid {{
  name "floor"
  children [ Shape {{ appearance PBRAppearance {{ baseColor 0.55 0.56 0.58 roughness 1 metalness 0 }} geometry DEF FLOOR_GEO Plane {{ size 6 6 }} }} ]
  boundingObject USE FLOOR_GEO
}}
SafetyFence {{ translation 0.6 0 0 }}
DEF SCARA_PEDESTAL Solid {{
  translation {SCARA_BASE[0]} {SCARA_BASE[1]} {SCARA_BASE[2] / 2}
  name "SCARA pedestal"
  children [ Shape {{ appearance PBRAppearance {{ baseColor 0.3 0.32 0.35 roughness 0.6 metalness 0.4 }} geometry DEF PEDESTAL Box {{ size 0.3 0.3 {SCARA_BASE[2]} }} }} ]
  boundingObject USE PEDESTAL
}}
DEF SCARA Scara4Axis {{
  translation {SCARA_BASE[0]} {SCARA_BASE[1]} {SCARA_BASE[2]}
  name "scara"
  controller "cell_robot"
  controllerArgs [ "../../motions/scara_cell.motion" ]
  initialPosition [ {qs} ]
  transparency {tr}
  showJointFrames {frames}
}}
DEF ARM6 Arm6Dof {{
  translation {ARM_BASE[0]} {ARM_BASE[1]} {ARM_BASE[2]}
  rotation 0 0 1 {ARM_YAW:.5f}
  name "arm6"
  controller "cell_robot"
  controllerArgs [ "../../motions/arm6_cell.motion" ]
  initialPosition [ {qa} ]
  transparency {tr}
  showJointFrames {frames}
}}
DEF CONVEYOR BeltConveyor {{
  translation {I[0]} {I[1]} 0
  name "conveyor"
  slats [
{slats}
  ]
}}
DEF OUTPUT_BIN OutputBin {{
  translation {O[0]} {O[1]} 0
}}
""" + "\n".join(cubes) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--plain", action="store_true", help="opaque robots, no joint frames")
    ap.add_argument("--out", default=os.path.join(ROOT, "worlds", "robot_cell.wbt"))
    a = ap.parse_args()
    with open(a.out, "w") as f:
        f.write(build(a.plain))
    print("wrote", os.path.relpath(a.out, ROOT))


if __name__ == "__main__":
    main()
