"""Write the example worlds 02-04 (worlds/example_*.wbt) from the PROTOs.

    02  SCARA pick & place A -> B -> A on a work table
    03  6-axis arm pick & place A -> B -> A (full IK: position + vertical gripper)
    04  6-axis arm pick & place around a 0.30 m pillar and over/around a low wall
        (A* on the whole-arm collision model, see tools/examples/gen_arm6_obstacles.py)
The robots run controllers/motion_player with the motion of motions/examples/.
"""
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")


def first_pose(name, n):
    with open(os.path.join(ROOT, "motions", "examples", name)) as f:
        f.readline()
        return " ".join(f"{float(v):g}" for v in f.readline().strip().split(",")[2:2 + n])


def header(protos, viewpoint):
    ext = "\n".join(f'EXTERNPROTO "../protos/{p}.proto"' for p in protos)
    return f"""#VRML_SIM R2025a utf8
# Generated by tools/build_examples.py

{ext}

WorldInfo {{
  basicTimeStep 8
  coordinateSystem "ENU"
  contactProperties [
    ContactProperties {{ material1 "finger" material2 "cube" coulombFriction [ 2 ] softCFM 0.0001 }}
  ]
}}
Viewpoint {{ {viewpoint} }}
Background {{ skyColor [ 0.6 0.62 0.65 ] }}
DirectionalLight {{ direction -0.5 -0.5 -1 intensity 2 castShadows TRUE }}
DEF FLOOR Solid {{
  name "floor"
  children [ Shape {{ appearance PBRAppearance {{ baseColor 0.8 0.8 0.8 roughness 1 }} geometry DEF FLOOR_GEO Plane {{ size 4 4 }} }} ]
  boundingObject USE FLOOR_GEO
}}
DEF WORKTABLE Solid {{
  translation 0.45 0 0.025
  name "work table"
  children [ Shape {{ appearance PBRAppearance {{ baseColor 0.85 0.85 0.8 roughness 0.6 metalness 0 }} geometry Box {{ size 0.5 0.6 0.05 }} }} ]
  boundingObject Box {{ size 0.5 0.6 0.05 }}
}}
DEF MARK_A Pose {{ translation 0.35 0.15 0.0505 children [ Shape {{ appearance PBRAppearance {{ baseColor 0.2 0.7 0.3 roughness 1 metalness 0 }} geometry Plane {{ size 0.06 0.06 }} }} ] }}
DEF MARK_B Pose {{ translation 0.55 -0.15 0.0505 children [ Shape {{ appearance PBRAppearance {{ baseColor 0.2 0.4 0.9 roughness 1 metalness 0 }} geometry Plane {{ size 0.06 0.06 }} }} ] }}
DEF CUBE Solid {{
  translation 0.35 0.15 0.0702
  name "cube"
  contactMaterial "cube"
  children [ Shape {{ appearance PBRAppearance {{ baseColor 0.9 0.75 0.1 roughness 0.5 metalness 0 }} geometry Box {{ size 0.04 0.04 0.04 }} }} ]
  boundingObject Box {{ size 0.04 0.04 0.04 }}
  physics Physics {{ density -1 mass 0.05 }}
}}
"""


def robot(proto, defname, name, motion, n):
    return f"""DEF {defname} {proto} {{
  name "{name}"
  controller "motion_player"
  controllerArgs [ "../../motions/examples/{motion}" ]
  initialPosition [ {first_pose(motion, n)} ]
}}
"""


def planned_path():
    with open(os.path.join(ROOT, "motions", "examples", "arm6_obstacles_path.txt")) as f:
        pts = [line.strip() for line in f if line.strip()]
    return (f"DEF PLANNED_PATH Shape {{\n  castShadows FALSE\n  appearance Appearance {{ material Material {{ diffuseColor 0 0 0 "
            f"emissiveColor 0.1 0.8 0.2 }} }}\n  geometry IndexedLineSet {{\n    coord Coordinate {{ point [ {', '.join(pts)} ] }}\n"
            f"    coordIndex [ {' '.join(str(i) for i in range(len(pts)))} ]\n  }}\n}}\n")


OBSTACLES = """DEF PILLAR Solid {
  translation 0.47 0 0.2
  name "pillar"
  children [ Shape { appearance PBRAppearance { baseColor 0.85 0.2 0.15 roughness 0.6 metalness 0 } geometry Box { size 0.06 0.06 0.3 } } ]
  boundingObject Box { size 0.06 0.06 0.3 }
}
DEF LOW_WALL Solid {
  translation 0.51 -0.07 0.085
  name "low wall"
  children [ Shape { appearance PBRAppearance { baseColor 0.45 0.45 0.5 roughness 0.7 metalness 0 } geometry Box { size 0.1 0.03 0.07 } } ]
  boundingObject Box { size 0.1 0.03 0.07 }
}
"""

WORLDS = {
    "example_02_scara_pick_place.wbt":
        header(["Scara4Axis"], "orientation -0.27612 0.13085 0.95217 2.29386 position 1.25 -1.1 1.05")
        + robot("Scara4Axis", "SCARA", "scara", "scara_pick_place.motion", 4),
    "example_03_arm6_pick_place.wbt":
        header(["Arm6Dof"], "orientation -0.20955 0.0868 0.97394 2.37469 position 1.35 -1.05 0.95")
        + robot("Arm6Dof", "ARM6", "arm6", "arm6_pick_place.motion", 6),
    "example_04_arm6_obstacles.wbt":
        header(["Arm6Dof"], "orientation 0.2527 -0.2263 -0.9407 4.3702 position 0.735 -1.327 1.018")
        + robot("Arm6Dof", "ARM6", "arm6", "arm6_obstacles.motion", 6) + OBSTACLES + planned_path(),
}

if __name__ == "__main__":
    for name, text in WORLDS.items():
        with open(os.path.join(ROOT, "worlds", name), "w") as f:
            f.write(text)
        print("wrote worlds/" + name)
